"""
SCAI-SCI Gait Dataset - CameraHMR to SMPL Sequence Pipeline
===========================================================
This script processes per-frame 3D human mesh recovery outputs generated by
CameraHMR (the benchmarked model for clinical SCI gait estimation) and
aggregates them into continuous, aligned SMPL sequence files (.pkl).

Author:
    Shreyasvi Natraj

Project Leadership:
    Shreyasvi Natraj (Lead)
    Diego Paez-Granados (Principal Investigator)

Affiliations:
    Spinal Cord Artificial Intelligence (SCAI) Lab, ETH Zürich, Switzerland
    Swiss Paraplegic Research, Nottwil, Switzerland

Pipeline Overview:
1. (Optional) Organizes raw frame outputs (.png, .obj, .pkl) into structured subfolders.
2. Loads per-frame CameraHMR predictions (pose, orientation, shape betas, translation).
3. Uses the SMPL body model via `smplx` to recover 3D joint centers (24, 3) and mesh vertices (6890, 3).
4. Aligns coordinate systems to standard biomechanical conventions (Y-up inversion & orientation composition).
5. Merges the frames into one sequence dictionary per video (.pkl).

Usage:
    # Sort raw CameraHMR output files into subfolders first:
    python scripts/camerahmr_pipeline.py --organize --input_dir /path/to/camerahmr_raw

    # Build one SMPL sequence per video:
    python scripts/camerahmr_pipeline.py --input_dir /path/to/camerahmr_raw/pkl_output \
                                        --output_dir /path/to/smpl_sequences \
                                        --gender male \
                                        --smpl_model_dir smpl_models/

The released files were further renamed, flattened and de-duplicated by the release
toolkit; see scripts/README.md. Their translation (trans) is zero in every frame.
"""

