import os
import sys
import glob
import shutil
import pickle
import argparse
from collections import defaultdict
import numpy as np
from scipy.spatial.transform import Rotation


def organize_output_directory(target_dir):
    """
    Sorts loose per-frame files into images/, obj_output/, and pkl_output/ subdirectories.
    """
    ext_map = {
        ".jpg": "images",
        ".png": "images",
        ".obj": "obj_output",
        ".pkl": "pkl_output",
    }
    print(f"\n[Organize] Sorting files in: {target_dir}")
    for sub in set(ext_map.values()):
        os.makedirs(os.path.join(target_dir, sub), exist_ok=True)

    moved_count = defaultdict(int)
    loose_files = [f for f in os.listdir(target_dir) if os.path.isfile(os.path.join(target_dir, f))]

    for fname in loose_files:
        ext = os.path.splitext(fname)[1].lower()
        if ext in ext_map:
            src = os.path.join(target_dir, fname)
            dst = os.path.join(target_dir, ext_map[ext], fname)
            shutil.move(src, dst)
            moved_count[ext_map[ext]] += 1

    for folder, count in moved_count.items():
        print(f"  -> Moved {count} files to {folder}/")
    print("[Organize] Completed.")


def process_smpl_frame(data, smpl_model, num_joints=24):
    """
    Processes SMPL parameters for a single frame from CameraHMR output.

    Args:
        data (dict): Dictionary containing CameraHMR predictions.
        smpl_model: Instantiated smplx SMPL model.
        num_joints (int): Number of SMPL joints to retain (default: 24).

    Returns:
        dict: Processed frame parameters with 3D joints and vertices.
    """
    import torch
    from pytorch3d import transforms

    # Extract tensors and handle potential batch dimensions
    if len(data['body_pose']) > 1:
        betas = torch.tensor(data['betas'][0].to('cpu'), dtype=torch.float32).unsqueeze(0)
        global_orient = torch.tensor(data['global_orient'][0].to('cpu'), dtype=torch.float32).unsqueeze(0)
        pred_pose = torch.tensor(data['body_pose'][0].to('cpu'), dtype=torch.float32).unsqueeze(0)
        trans = torch.tensor(data['trans'][0].to('cpu'), dtype=torch.float32).unsqueeze(0) if 'trans' in data else torch.zeros(1, 3, dtype=torch.float32)
    else:
        betas = data['betas'].to('cpu') if isinstance(data['betas'], torch.Tensor) else torch.tensor(data['betas'], dtype=torch.float32)
        global_orient = data['global_orient'].to('cpu') if isinstance(data['global_orient'], torch.Tensor) else torch.tensor(data['global_orient'], dtype=torch.float32)
        pred_pose = data['body_pose'].to('cpu') if isinstance(data['body_pose'], torch.Tensor) else torch.tensor(data['body_pose'], dtype=torch.float32)
        trans = data['trans'].to('cpu') if ('trans' in data and isinstance(data['trans'], torch.Tensor)) else torch.zeros(1, 3, dtype=torch.float32)

    # Convert rotation matrices to axis-angle representation if needed
    if pred_pose.ndim >= 3 and pred_pose.shape[-1] == 3 and pred_pose.shape[-2] == 3:
        pred_pose = transforms.matrix_to_axis_angle(pred_pose)
    if global_orient.ndim >= 3 and global_orient.shape[-1] == 3 and global_orient.shape[-2] == 3:
        global_orient = transforms.matrix_to_axis_angle(global_orient)

    pred_pose = pred_pose.reshape(1, 69)
    global_orient = global_orient.reshape(1, 3)
    trans = trans.reshape(1, 3)

    # Forward pass through SMPL model
    output = smpl_model(
        betas=betas,
        body_pose=pred_pose,
        global_orient=global_orient,
        transl=trans,
        return_verts=True
    )

    pred_joints = output.joints.detach().cpu().numpy()[0, :num_joints, :]
    pred_vertices = output.vertices.detach().cpu().numpy()[0]

    return {
        'joints': pred_joints,          # (24, 3)
        'vertices': pred_vertices,      # (6890, 3)
        'body_pose': pred_pose[0].numpy(),      # (69,)
        'global_orient': global_orient[0].numpy(), # (3,)
        'betas': betas[0].numpy(),      # (10,)
        'trans': trans[0].numpy()       # (3,)
    }


def create_smpl_sequences(input_folder, output_folder, smpl_model_path, gender='male'):
    """
    Aggregates individual CameraHMR frame .pkl files into unified temporal sequence files.
    """
    try:
        import smplx
    except ImportError:
        print("Error: `smplx` is required to build SMPL sequences. Install via: pip install smplx")
        sys.exit(1)

    if not os.path.exists(smpl_model_path):
        print(f"Error: SMPL model file not found at: {smpl_model_path}")
        print("Please download SMPL_MALE.pkl / SMPL_FEMALE.pkl from https://smpl.is.tue.mpg.de/")
        sys.exit(1)

    os.makedirs(output_folder, exist_ok=True)

    # Load SMPL model instance
    print(f"[SMPL Init] Loading {gender.upper()} model from: {smpl_model_path}")
    smpl_model = smplx.create(
        model_path=os.path.dirname(smpl_model_path),
        model_type='smpl',
        gender=gender
    )

    # Find all frame pickle files
    files = sorted(glob.glob(os.path.join(input_folder, "*.pkl")), key=len)
    if not files:
        print(f"No .pkl files found in {input_folder}")
        return

    # Group files by subject identifier (prefix before '_frame_')
    subject_files = defaultdict(dict)
    for file in files:
        filename = os.path.basename(file)
        if "_frame_" not in filename:
            continue
        parts = filename.split("_frame_")
        subject = parts[0]
        frame_str = parts[1].split("_")[0]
        try:
            frame_id = int(frame_str)
        except ValueError:
            continue
        subject_files[subject][file] = frame_id

    print(f"Found {len(subject_files)} subjects to process in {input_folder}.")

    for subject, file_dict in subject_files.items():
        n_frames = len(file_dict)
        print(f"\n--- Processing subject: {subject} ({n_frames} frames) ---")

        joints_list = []
        vertices_list = []
        body_pose_list = []
        global_orient_list = []
        betas_list = []
        trans_list = []
        frame_ids = []

        # Process frames in chronological order
        for file, frame_id in sorted(file_dict.items(), key=lambda x: x[1]):
            with open(file, 'rb') as f:
                raw_frame_data = pickle.load(f)

            processed = process_smpl_frame(raw_frame_data, smpl_model)

            # Invert Y-axis coordinates for biomechanical consistency
            joints = processed['joints'].copy()
            joints[:, 1] *= -1
            vertices = processed['vertices'].copy()
            vertices[:, 1] *= -1
            trans = processed['trans'].copy()
            trans[1] *= -1

            # Flip global orientation: 180-degree rotation around X-axis
            global_orient = processed['global_orient'].copy()
            flip_rot = Rotation.from_euler('x', 180, degrees=True).as_rotvec()
            global_rot = Rotation.from_rotvec(global_orient)
            flip_rot_obj = Rotation.from_rotvec(flip_rot)
            new_global_rot = flip_rot_obj * global_rot
            global_orient = new_global_rot.as_rotvec()

            body_pose = processed['body_pose'].copy()
            betas = processed['betas'].copy()

            joints_list.append(joints)
            vertices_list.append(vertices)
            body_pose_list.append(body_pose)
            global_orient_list.append(global_orient)
            betas_list.append(betas)
            trans_list.append(trans)
            frame_ids.append(frame_id)

        # Assemble unified sequence dictionary
        sequence_data = {
            'frame_ids': np.array(frame_ids),
            'joints': np.stack(joints_list),          # (N_frames, 24, 3)
            'vertices': np.stack(vertices_list),      # (N_frames, 6890, 3)
            'body_pose': np.stack(body_pose_list),    # (N_frames, 69)
            'global_orient': np.stack(global_orient_list), # (N_frames, 3)
            'betas': np.stack(betas_list),            # (N_frames, 10)
            'trans': np.stack(trans_list)             # (N_frames, 3)
        }

        output_pkl = os.path.join(output_folder, f"{subject}_smpl_sequence.pkl")
        with open(output_pkl, 'wb') as f:
            pickle.dump(sequence_data, f)
        print(f"  [Saved] {output_pkl} ({sequence_data['joints'].shape})")


def main():
    parser = argparse.ArgumentParser(
        description="SCAI-SCI Gait Dataset: CameraHMR to SMPL Sequence Processing & Aggregation Pipeline."
    )
    parser.add_argument(
        "--input_dir", type=str, required=True,
        help="Input folder containing per-frame CameraHMR .pkl files (or raw outputs if --organize)."
    )
    parser.add_argument(
        "--output_dir", type=str, default=None,
        help="Output folder where aggregated sequence .pkl files will be written."
    )
    parser.add_argument(
        "--gender", type=str, choices=["male", "female"], default="male",
        help="Subject biological sex ('male' or 'female') for SMPL model selection."
    )
    parser.add_argument(
        "--smpl_model_dir", type=str, default="smpl_models",
        help="Directory containing SMPL_MALE.pkl and SMPL_FEMALE.pkl."
    )
    parser.add_argument(
        "--organize", action="store_true",
        help="Organize raw loose files into images/, obj_output/, and pkl_output/ subdirectories."
    )

    args = parser.parse_args()

    if args.organize:
        organize_output_directory(args.input_dir)
        if not args.output_dir:
            return

    if not args.output_dir:
        parser.error("--output_dir is required when generating SMPL sequences.")

    model_filename = f"SMPL_{args.gender.upper()}.pkl"
    smpl_model_path = os.path.join(args.smpl_model_dir, model_filename)

    create_smpl_sequences(
        input_folder=args.input_dir,
        output_folder=args.output_dir,
        smpl_model_path=smpl_model_path,
        gender=args.gender
    )


if __name__ == "__main__":
    main()
